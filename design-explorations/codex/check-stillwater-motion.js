// Open 11-stillwater-motion.html with agent-browser, then pipe this file to `eval --stdin`.
(async()=>{
  const frame=document.getElementById('prototype');
  const doc=frame.contentDocument;
  const app=doc.getElementById('live-app');
  const api=frame.contentWindow.motionStudy;
  const results=[];
  const assert=(condition,message)=>{if(!condition)throw new Error(message);results.push(message);};
  const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const click=selector=>{const el=app.querySelector(selector);if(!el)throw new Error('Missing control: '+selector);el.click();};
  api.reset();api.setMode('lively');
  if(api.getStatus().lang==='ar')api.language();
  assert(api.getStatus().target===null,'Starts online');
  click('[data-action=device][data-target=tv]');
  assert(api.getStatus().sheet==='device'&&doc.activeElement.closest('.sheet'),'Device sheet receives focus');
  click('.sheet [data-action=compose-device]');
  click('.sheet [data-action=preset][data-minutes="10"]');
  assert(app.querySelector('.sheet input[name=minutes]').value==='10','10-minute preset updates the field');
  click('.sheet [data-action=mode-indefinite]');
  assert(!app.querySelector('.sheet input[name=minutes]'),'Indefinite mode removes minute input');
  click('.sheet [data-action=mode-timed]');
  assert(app.querySelectorAll('.segment-pill').length===1,'Mode change has one selection indicator');
  app.querySelector('.sheet .pauseform').requestSubmit();
  assert(api.getStatus().busy&&api.getStatus().target===null,'No confirmed pause while checking');
  assert(api.demo('pause')===false,'Repeated requests are rejected while busy');
  await wait(1150);
  assert(api.getStatus().target==='tv'&&!api.getStatus().busy,'TV pause appears after confirmation');
  click('[data-action=targets]');
  click('.sheet [data-action=device][data-target=phone]');
  click('.sheet [data-action=compose-device]');
  app.querySelector('.sheet .pauseform').requestSubmit();
  assert(api.getStatus().sheet==='replace'&&api.getStatus().target==='tv','Changing target asks to replace the pause');
  click('.sheet [data-action=close]');
  await wait(200);
  assert(api.getStatus().target==='tv'&&!app.querySelector('.sheet'),'Cancelling replacement keeps the existing pause');
  click('[data-action=resume]');
  assert(api.getStatus().target==='tv'&&api.getStatus().busy,'Pause remains until resume is confirmed');
  await wait(1150);
  assert(api.getStatus().target===null&&app.querySelectorAll('.device').length===4,'Resume restores the online list');
  api.language();
  assert(doc.getElementById('live-app').dir==='rtl','Arabic switches the app to RTL');
  api.demo('navigation');
  const navigation=app.querySelector('.appmain').getAnimations()[0];
  if(!api.getStatus().reduced)assert(navigation?.effect.getKeyframes()[0].transform==='translateX(-18px)','RTL navigation mirrors movement');
  api.demo('duration');
  const pill=app.querySelector('.segment-pill');
  const selected=app.querySelector('.segmented .selected');
  assert(Math.abs(pill.offsetLeft-selected.offsetLeft)<1,'RTL selection indicator aligns with its button');
  app.style.width='90%';
  frame.contentWindow.dispatchEvent(new frame.contentWindow.Event('resize'));
  const resizedPill=app.querySelector('.segment-pill');
  assert(Math.abs(resizedPill.offsetLeft-selected.offsetLeft)<1&&Math.abs(resizedPill.offsetWidth-selected.offsetWidth)<1,'Selection indicator realigns after resize');
  app.style.width='';frame.contentWindow.dispatchEvent(new frame.contentWindow.Event('resize'));
  doc.dispatchEvent(new frame.contentWindow.KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
  await wait(200);
  assert(api.getStatus().sheet===null&&!app.querySelector('.sheet'),'Escape closes the sheet and removes its exit layer');
  api.setMode('off');api.demo('duration');
  assert(api.getStatus().animations===0,'Still mode runs no motion effects');
  api.setMode('lively');
  if(api.getStatus().reduced){api.entrance();assert(api.getStatus().animations===0,'System reduced motion overrides Lively');}
  api.reset();api.language();
  await wait(400);
  assert(!app.querySelector('.exiting-sheet,.touch-ripple'),'Temporary animation elements are cleaned up');
  return {passed:results.length,reducedMotion:api.getStatus().reduced,results};
})()
